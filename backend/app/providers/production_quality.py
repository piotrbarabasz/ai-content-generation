"""Local media-inspection boundary, independent of encoders and AI services."""
from typing import Protocol


class QAInspector(Protocol):
    def identity(self) -> dict: ...
    async def probe(self, source, root, config, *, canceled, progress) -> dict: ...
    async def decode(self, source, root, config, *, canceled, progress) -> dict: ...
    async def audio(self, source, root, config, *, canceled, progress) -> dict: ...
    async def visual(self, source, root, config, *, canceled, progress) -> dict: ...
    async def frames(self, source, root, shots, config, *, canceled, progress) -> list: ...
    async def frame(self, source, root, time, config, *, canceled, index=0) -> dict: ...
