"""Local rendering boundary; applications do not select concrete encoders."""
from typing import Protocol

class ShortsRenderer(Protocol):
    def identity(self) -> dict: ...
    async def render(self, root, evidence, start, end, shots, style, segments, *, canceled, progress, audio_bounds=None) -> dict: ...
    async def preview(self, root, evidence, time, shots, style, segments, *, canceled, relative=0) -> bytes: ...


class DirectorRenderer(Protocol):
    def identity(self) -> dict: ...
    async def render(self, root, storyboard, audio, style, segments, *, logo, canceled, progress) -> dict: ...
    async def preview(self, root, storyboard, style, segments, *, canceled) -> bytes: ...
